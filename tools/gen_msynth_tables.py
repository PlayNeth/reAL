"""gen_msynth_tables.py <dmsynth.dll> <data.bin> > src/music/msynth_tables.h
Lookup tables of Microsoft's software synth (dmsynth.dll 5.3.x): the static ones from the file, the ones it builds
at start-up (pow/sin based) from a dump of its .data section taken after initialisation (tools/dmgt, DMGT_DATADUMP)."""
import sys, struct, pefile
pe = pefile.PE(sys.argv[1]); base = pe.OPTIONAL_HEADER.ImageBase
img = bytearray(pe.get_memory_mapped_image())
d = open(sys.argv[2], 'rb').read(); rva, sz = struct.unpack_from('<II', d); img[rva:rva + sz] = d[8:8 + sz]
def arr(addr, n, fmt='i'):
    s = struct.calcsize(fmt)
    return [struct.unpack_from('<' + fmt, img, addr - base + s * k)[0] for k in range(n)]
def emit(ctype, name, vals, per=12):
    print(f'static const {ctype} {name}[{len(vals)}] = {{')
    for i in range(0, len(vals), per):
        print('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    print('};')
print('/* generated by tools/gen_msynth_tables.py - do not edit */')
emit('int32_t', 'ms_db2lin', arr(0x7749a558 - 4000, 1001))            # index (centibels) -1000..0 -> 0..4095
emit('int32_t', 'ms_cent_fine', arr(0x77499420 - 400, 201))           # -100..100 cents -> 4096*2^(c/1200)
emit('int32_t', 'ms_cent_oct', arr(0x77498fc8 - 4 * 48, 97))          # -48..48 semitones
emit('int16_t', 'ms_sine', arr(0x77498d08, 256, 'h'))
emit('int16_t', 'ms_egatk', arr(0x77498b70, 201, 'h'))
emit('int32_t', 'ms_pan', arr(0x77499090, 128))
emit('int32_t', 'ms_cc2mb', arr(0x77494060, 128))                     # CC7/CC11/velocity -> millibels
emit('int32_t', 'ms_send2mb', arr(0x77494260, 128))                   # CC91/CC93 -> millibels
emit('int32_t', 'ms_flt_b0', arr(0x774970e0, 16 * 89))
emit('int32_t', 'ms_flt_a1', arr(0x77494460, 16 * 89))
emit('int32_t', 'ms_flt_a2', arr(0x77495aa0, 16 * 89))
print('static const int16_t ms_hold_level = %d;' % arr(0x77498d00, 1, 'h')[0])
emit('uint8_t', 'ms_chanmap', [v & 0xff for v in arr(0x77494020, 16)])
