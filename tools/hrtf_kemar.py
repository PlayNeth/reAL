#!/usr/bin/env python3
"""Generate src/hrtf_kemar_data.h, reAL's built-in HRTF (hrtf=builtin), from the MIT KEMAR measurements.

usage: hrtf_kemar.py <mit-hrtf-lib>/source/diffuse/mit_hrtf_diffuse_48000.h src/hrtf_kemar_data.h

Source: the KEMAR "compact" set (Bill Gardner and Keith Martin, MIT Media Lab, 1994), diffuse-field equalised and
resampled to 48 kHz by Aristotel Digenis' mit-hrtf-lib (https://github.com/zodsoft/mit-hrtf-lib, MIT licence).
The set holds the right half of each elevation ring (azimuth 0..180); the left half is its mirror image, ears swapped.

For each response, as tools/hrtf_build.py does for a measured set:
* the onset of each ear (first sample above 10% of its peak, less 2) becomes a whole-sample delay, counted from the
  earliest onset of the whole set, and the 64 taps from there are kept (the last 8 faded out);
* everything is scaled by one factor, so that the mean energy of the horizontal ring (both ears) is 0.82, the level of
  the ALchemy measurement reAL was tuned with, and stored as 16-bit integers.
"""
import re
import sys

import numpy as np

TAPS = 64
MARGIN = 2
FADE = 8
TARGET_E0 = 0.82
RINGS = {-40: 56, -30: 60, -20: 72, -10: 72, 0: 72, 10: 72, 20: 72, 30: 60, 40: 56, 50: 45, 60: 36, 70: 24, 80: 12,
         90: 1}


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding="latin-1").read()
    ents = {}
    for m in re.finditer(r"//\s*H(-?\d+)e(\d+)a\.wav\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}", text):
        el, az = int(m.group(1)), int(m.group(2))
        left = np.array([int(x) for x in m.group(3).split(",") if x.strip()], float) / 32768.0
        right = np.array([int(x) for x in m.group(4).split(",") if x.strip()], float) / 32768.0
        assert len(left) == len(right) == 140, (el, az)
        ents[(el, az)] = (left, right)
    assert len(ents) == 368, len(ents)

    # the stored half of each ring: full-ring index k = 0 .. n // 2, azimuth k * 360 / n (rounded as in the file names)
    rings = []
    for el in sorted(RINGS):
        n = RINGS[el]
        azs = sorted(a for e, a in ents if e == el)
        assert len(azs) == n // 2 + 1, (el, len(azs))
        for k, a in enumerate(azs):
            assert abs(a - k * 360.0 / n) < 1.0, (el, k, a)
        rings.append((el, n, azs))

    def onset(h):
        return max(int(np.flatnonzero(np.abs(h) > 0.1 * np.abs(h).max())[0]) - MARGIN, 0)

    base = min(onset(h) for lr in ents.values() for h in lr)
    fade = np.ones(TAPS)
    fade[TAPS - FADE:] = 0.5 + 0.5 * np.cos(np.pi * (np.arange(FADE) + 1) / FADE)
    out = []                                     # (el, k, delay_l, delay_r, coef_l, coef_r), rings in order
    for el, n, azs in rings:
        for k, a in enumerate(azs):
            d, c = [], []
            for h in ents[(el, a)]:
                o = onset(h)
                x = h[o:o + TAPS]
                x = np.pad(x, (0, TAPS - len(x))) * fade
                d.append(o - base)
                c.append(x)
            out.append((el, k, d[0], d[1], c[0], c[1]))

    e0 = []                                      # horizontal ring, full circle (mirrored halves count the same)
    n0 = RINGS[0]
    for el, k, dl, dr, cl, cr in out:
        if el == 0:
            e = (cl ** 2).sum() + (cr ** 2).sum()
            e0 += [e] if k in (0, n0 // 2) else [e, e]
    scale = np.sqrt(TARGET_E0 / np.mean(e0))
    peak = max(max(np.abs(cl).max(), np.abs(cr).max()) for *_, cl, cr in out) * scale
    q = 32767.0 / peak                           # integer = coefficient * q
    assert max(max(dl, dr) for _, _, dl, dr, _, _ in out) < 256

    with open(dst, "w", newline="\n") as f:
        f.write("/* reAL - built-in HRTF data (hrtf=builtin).  Generated by tools/hrtf_kemar.py: do not edit.\n")
        f.write(" *\n")
        f.write(" * MIT KEMAR HRTF measurements, \"compact\" set: Bill Gardner and Keith Martin, MIT Media Lab, 1994\n")
        f.write(" * (\"HRTF Measurements of a KEMAR Dummy-Head Microphone\", MIT Media Lab Perceptual Computing Technical\n")
        f.write(" * Report #280).  Provided by MIT without usage restrictions.\n")
        f.write(" * Diffuse-field equalised 48 kHz tables from mit-hrtf-lib, https://github.com/zodsoft/mit-hrtf-lib:\n")
        f.write(" *   Copyright (c) 2007 Aristotel Digenis, Copyright (c) 2014 greekgoddj.  MIT licence:\n")
        f.write(" *   Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated\n")
        f.write(" *   documentation files (the \"Software\"), to deal in the Software without restriction, including without limitation\n")
        f.write(" *   the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and\n")
        f.write(" *   to permit persons to whom the Software is furnished to do so, subject to the following conditions:\n")
        f.write(" *   The above copyright notice and this permission notice shall be included in all copies or substantial portions\n")
        f.write(" *   of the Software.\n")
        f.write(" *   THE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED\n")
        f.write(" *   TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE\n")
        f.write(" *   AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF\n")
        f.write(" *   CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER\n")
        f.write(" *   DEALINGS IN THE SOFTWARE.\n")
        f.write(" *\n")
        f.write(" * Each ring stores azimuths 0..180 (index k at k * 360 / n_az, clockwise from the front); the left half is the\n")
        f.write(" * mirror image with the ears swapped.  Delays are whole samples at 48 kHz; coefficient = value / KEMAR_Q. */\n\n")
        f.write("#define KEMAR_RATE  48000\n#define KEMAR_TAPS  %d\n#define KEMAR_RINGS %d\n#define KEMAR_HALF  %d\n"
                % (TAPS, len(rings), len(out)))
        f.write("#define KEMAR_Q     %.9gf\n\n" % q)
        f.write("static const struct { float el; uint16_t n_az; } kemar_rings[KEMAR_RINGS] = {\n   ")
        f.write(",".join(" { %d, %d }" % (el, n) for el, n, _ in rings))
        f.write("\n};\n\n")
        f.write("static const uint8_t kemar_delay[KEMAR_HALF][2] = {\n")
        for i in range(0, len(out), 16):
            f.write("    " + " ".join("{%d,%d}," % (o[2], o[3]) for o in out[i:i + 16]) + "\n")
        f.write("};\n\n")
        f.write("static const int16_t kemar_coef[KEMAR_HALF][2][KEMAR_TAPS] = {\n")
        for el, k, dl, dr, cl, cr in out:
            f.write("    { /* el %d, az %d */\n" % (el, round(k * 360.0 / RINGS[el])))
            for c in (cl, cr):
                v = np.clip(np.round(c * scale * q), -32768, 32767).astype(int)
                f.write("      { " + ",".join(str(x) for x in v) + " },\n")
            f.write("    },\n")
        f.write("};\n")
    print("wrote %s: %d rings, %d stored directions (%d with mirrors), %d taps, scale %.4f, base onset %d"
          % (dst, len(rings), len(out), sum(RINGS.values()), TAPS, scale, base))


if __name__ == "__main__":
    main()
